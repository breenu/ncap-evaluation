"""docs/deweathering_report.md: the Phase 5 results, generated from the full run (RQ2).

    python -m src.normalise.report

Every number comes from data/processed/deweathered/ (src.normalise.aggregate). Nothing here
compares NCAP with non-NCAP cities: deweathering is fitted per station without NCAP status.
"""

import json

import numpy as np
import pandas as pd

from src.common.paths import DOCS
from src.normalise.aggregate import OUT
from src.normalise.features import INPUTS, cfg
from src.normalise.pilot import FAM, POL, md_table


def weather_by_year(sy: pd.DataFrame) -> pd.DataFrame:
    """How much weather raised or lowered each year's annual mean, relative to typical 2015-2025
    weather: log(raw / deweathered) per valid station-year, centred per series (the smearing
    constant and any fixed offset drop out), median and IQR over stations, in %."""
    y = sy[(sy.variant == "q1_t75") & sy.valid & sy.dw.notna()].copy()
    y["w"] = np.log(y.raw / y.dw)
    y["w"] -= y.groupby(["sid", "pollutant"]).w.transform("mean")
    g = y.groupby(["pollutant", "year"]).w
    t = pd.DataFrame({"stations": g.size(), "median_pct": 100 * g.median(),
                      "q25_pct": 100 * g.quantile(0.25), "q75_pct": 100 * g.quantile(0.75)}).reset_index()  # fmt: skip
    return t.assign(note=np.where(t.year == 2020, "lockdown year: not removed by deweathering", ""))


def city_weather_share(cy: pd.DataFrame) -> pd.DataFrame:
    cy = cy.sort_values(["pollutant", "unit_id", "year"])
    k = [cy.pollutant, cy.unit_id]
    w = np.log(cy.raw).groupby(k).diff() - np.log(cy.dw).groupby(k).diff()
    w = w.where(cy.groupby(["pollutant", "unit_id"]).year.diff() == 1)
    d = cy.assign(w=100 * w.abs(), raw_change=100 * np.log(cy.raw).groupby(k).diff().abs()).dropna(subset=["w"])
    return d.groupby("pollutant").agg(
        city_year_pairs=("w", "size"), cities=("unit_id", "nunique"),
        median_abs_raw_change_pct=("raw_change", "median"), median_abs_weather_pct=("w", "median"),
        p90_abs_weather_pct=("w", lambda s: s.quantile(0.9)),
    ).reset_index()  # fmt: skip


def main() -> None:
    c = cfg()
    choice = json.loads((OUT / "family_choice.json").read_text(encoding="utf-8"))
    mets = pd.read_parquet(OUT / "series_metrics.parquet")
    sy = pd.read_parquet(OUT / "station_year.parquet")
    cy = pd.read_parquet(OUT / "city_year.parquet")
    cm = pd.read_parquet(OUT / "city_month.parquet")
    series = pd.read_csv(INPUTS / "main" / "series.csv")
    skipped = series[series.skipped.notna()] if "skipped" in series else series.iloc[:0]
    done = series[series.skipped.isna()] if "skipped" in series else series

    lab = lambda d: d.assign(**{k: d[k].map(v) for k, v in (("family", FAM), ("pollutant", POL)) if k in d})  # noqa: E731
    cov = done.groupby("pollutant").agg(series=("sid", "size"), median_fit_days=("n_fit", "median"),
                                        median_folds=("n_folds", "median"),
                                        no_cv_fold=("n_folds", lambda s: int((s == 0).sum()))).reset_index()  # fmt: skip
    sk = skipped.groupby(["pollutant", "skipped"]).size().rename("series").reset_index()
    r2 = mets.groupby(["family", "pollutant"]).r2_oos.describe(percentiles=[0.1, 0.25, 0.5, 0.75, 0.9])
    r2 = r2.rename(columns={"count": "series with CV"}).drop(columns=["mean", "std"]).reset_index()
    acf = mets.groupby(["family", "pollutant"])[[f"acf_oos_{k}" for k in range(1, 8)]].median().reset_index()
    div = mets[mets.family == choice["primary"]].dropna(subset=["D_pct"])
    dv = div.groupby("pollutant").agg(series=("D_pct", "size"), median_D_pct=("D_pct", "median"),
                                      p90_D_pct=("D_pct", lambda s: s.quantile(0.9)),
                                      diverging=("diverges", "sum")).reset_index()  # fmt: skip
    dv["share_diverging"] = dv.diverging / dv.series
    top = div.sort_values("D_pct", ascending=False).head(10)[["sid", "pollutant", "valid_years", "D_pct"]]
    wy = weather_by_year(sy)
    wy_w = wy.pivot_table(index="year", columns="pollutant", values="median_pct").reset_index()
    wy_w.columns = ["year"] + [f"{POL[p]}: median weather effect (%)" for p in wy_w.columns[1:]]
    cws = city_weather_share(cy)
    pct, f3 = "{:.1f}", "{:.3f}"
    other = choice["sensitivity"]

    text = f"""# Deweathering results (Phase 5, RQ2)

*Generated by `python -m src.normalise.report` from `data/processed/deweathered/`. Do not edit by hand. Method and rules: DEC-100 to DEC-107; pilot: [`deweathering_pilot.md`](deweathering_pilot.md). Nothing here compares NCAP with non-NCAP cities.*

## 1. Coverage

Station-pollutant series with ≥ {c['min_fit_days']} valid days to {c['fit_end']} (primary completeness rule), each deweathered by both families with {c['resamples_default']} weather draws (`{c['resample_scheme']}` scheme):

{md_table(lab(cov), {"median_fit_days": "{:.0f}", "median_folds": "{:.0f}"})}

Not deweathered:

{md_table(lab(sk)) if len(sk) else "None."}

## 2. Primary model family (registered rule, DEC-088)

Median out-of-sample R² (log scale, blocked forward-chaining CV by year, `{c['cv_trend']}` test-year trend, DEC-107) over all {choice['series_with_cv']} series with at least one CV fold: **LightGBM {choice['median_r2_oos']['lgbm']:.3f}, GAM {choice['median_r2_oos']['gam']:.3f}. Primary: {FAM[choice['primary']]}; {FAM[other]} is the sensitivity analysis.** The GAM predicts better in {choice['series_where_gam_better']} of {choice['series_with_cv']} series.

By pollutant: {'; '.join(f"{POL[p]}: LightGBM {v['lgbm']:.3f}, GAM {v['gam']:.3f}" for p, v in choice['median_r2_oos_by_pollutant'].items())}.

Distribution of out-of-sample R²:

{md_table(lab(r2), {k: f3 for k in ["min", "10%", "25%", "50%", "75%", "90%", "max"]} | {"series with CV": "{:.0f}"})}

Residual autocorrelation (median over series, out-of-sample, lags 1–7):

{md_table(lab(acf), {k: "{:.2f}" for k in acf.columns if k.startswith("acf")})}

## 3. Where the two families diverge

D = the largest gap, over valid years, between the two families' deweathered annual series (each relative to its own mean; log scale, as %). A series diverges if D > {c['divergence_flag_pct']}%.

{md_table(lab(dv), {"median_D_pct": pct, "p90_D_pct": pct, "share_diverging": "{:.2f}"})}

Largest divergences:

{md_table(lab(top), {"D_pct": pct})}

Diverging series stay in the analysis; the Phase 7 "other family" sensitivity check re-runs every ground estimate with {FAM[other]}.

## 4. How much weather moved annual numbers

Weather effect in a year = log(raw annual mean / deweathered annual mean) per valid station-year, centred within each series (a positive value: that year's weather made the annual mean higher than typical 2015–2025 weather would have). Median over stations valid that year:

{md_table(wy_w, {k: "{:+.1f}" for k in wy_w.columns if k != "year"})}

Full table with station counts and interquartile ranges: `data/processed/deweathered/` via `weather_by_year()`. 2020 is flagged throughout: its fall in raw PM is mostly the lockdown, an emissions change, and deweathering leaves it in.

City level (all-station city-year means, consecutive valid years): how large year-on-year changes are, and how large their weather part is.

{md_table(lab(cws), {"median_abs_raw_change_pct": pct, "median_abs_weather_pct": pct, "p90_abs_weather_pct": pct})}

## 5. Outputs

`data/processed/deweathered/`: `series_metrics`, `family_choice.json`, `station_day`, `station_year` (all four completeness variants), `station_month`, `city_month` ({cm.unit_id.nunique()} urban centres), `city_year` ({cy.unit_id.nunique()} urban centres). City series are all-station means over stations inside the urban-centre polygon (DEC-105); the balanced panel is Phase 6. Figure 3: `reports/figures/fig3_deweathered.png`.
"""
    (DOCS / "deweathering_report.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
