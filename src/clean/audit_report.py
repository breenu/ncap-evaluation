"""docs/audit_report.md: the Phase 3 station audit (RQ1), generated. Every number is read from a
pipeline output; nothing is typed by hand (project rule: every number in a document is generated by the pipeline).

BLINDING: nothing here compares NCAP with non-NCAP units.

    python -m src.clean.audit_report
"""

import geopandas as gpd
import numpy as np
import pandas as pd

from src.common.paths import DOCS, INTERIM, PROCESSED, params

AUDIT = INTERIM / "audit"
EDA = INTERIM / "eda"


def md(df: pd.DataFrame, digits: int = 2) -> str:
    d = df.copy()
    for c in d.columns:
        if c in ("year", "first_year", "month"):
            d[c] = d[c].map(
                lambda v: "" if pd.isna(v) else f"{int(v)}" if isinstance(v, int | float) else v
            )
        elif d[c].dtype.kind == "f":
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:,.{digits}f}")
        elif d[c].dtype.kind in "iu" and c not in ("year", "first_year", "month"):
            d[c] = d[c].map(lambda v: f"{v:,}")
    head = "| " + " | ".join(map(str, d.columns)) + " |\n|" + "---|" * len(d.columns) + "\n"
    return head + "\n".join(
        "| " + " | ".join(str(v) for v in r) + " |" for r in d.itertuples(index=False)
    )


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def build() -> str:
    P = params()
    stations = pd.read_csv(PROCESSED / "stations.csv")
    q = pd.read_parquet(PROCESSED / "station_year_quality.parquet")
    q25 = q[q.year <= 2025]
    fc = pd.read_csv(AUDIT / "flag_counts.csv")
    ceil = pd.read_csv(AUDIT / "ceilings.csv")
    cp = pd.read_csv(AUDIT / "changepoints.csv", parse_dates=["date"])
    cal = pd.read_csv(AUDIT / "changepoint_calibration.csv")
    sp = pd.read_csv(AUDIT / "spatial_station_year.csv")
    vs = pd.read_csv(AUDIT / "valid_station_years.csv")
    mm = pd.read_csv(AUDIT / "missingness_models.csv")
    mb = pd.read_csv(AUDIT / "missingness_bias.csv")
    mo = pd.read_csv(AUDIT / "missingness_by_month.csv")
    ent = pd.read_csv(EDA / "entrants.csv")
    gs = pd.read_csv(EDA / "ground_vs_satellite.csv")
    uy = pd.read_parquet(PROCESSED / "unit_year_sat.parquet")
    units = gpd.read_file(INTERIM / "sat_units.gpkg", ignore_geometry=True)
    hours = fc[fc.pollutant.isin(["pm25", "pm10"])]

    L = ["# Station data-quality audit (RQ1)", "",
         "*Generated by `python -m src.clean.audit_report` from pipeline outputs. Do not edit by hand. "
         "Blinding: nothing in this report compares NCAP with non-NCAP cities.*", ""]  # fmt: skip

    # 1 scope
    first = pd.read_csv(EDA / "station_first_year.csv")
    L += ["## 1. What was audited", "",
          f"{len(stations)} CPCB continuous stations (CAAQMS), {P['windows']['ground_start']} to {P['windows']['ground_end']} "
          "(Indian dates). 15-minute PM2.5 and PM10 from the CPCB mirror to the end of 2025 and from OpenAQ for "
          "January-March 2026, on the corrected clock (DEC-054). Stations with any PM data by year of first data:", "",
          md(first.groupby("first_year").size().rename("stations").reset_index()), ""]  # fmt: skip

    # 2 source checks
    L += ["## 2. Is the source trustworthy?", "",
          "The mirror was checked against OpenAQ's independent copy of the same CPCB data at every overlapping "
          "station-year (`docs/mirror-openaq-crosscheck.md`). 2019-2021 values are identical; IMD-operated stations "
          "differ at 15 minutes but agree on daily means; OpenAQ's March 2018 PM2.5 is an index, not a "
          "concentration (DEC-057). Station coordinates were settled from identical values "
          "(`docs/station_metadata_review.md`, DEC-058, DEC-059, DEC-067): "
          + ", ".join(f"{k} {v}" for k, v in stations.coord_quality.value_counts().items())
          + f"; {int(stations.decision_needed.sum())} stations await a decision.", ""]  # fmt: skip

    # 3 impossible values and ceilings
    tot_q = hours.groupby("pollutant")[
        ["quarters_kept", "quarters_impossible", "quarters_ceiling"]
    ].sum()
    tot_q["pct_removed"] = (
        100 * (tot_q.quarters_impossible + tot_q.quarters_ceiling) / tot_q.sum(axis=1)
    )
    imp = hours.groupby("year")[["quarters_impossible"]].sum()
    imp_years = imp[imp.quarters_impossible > 0]
    val = pd.read_csv(INTERIM / "crosscheck" / "validation_level.csv")
    v25 = val[val.year == 2025].iloc[0]
    L += ["## 3. Impossible values and instrument ceilings (15-minute values)", "",
          f"Values at or below zero: {int(imp.quarters_impossible.sum()):,} 15-minute values, all in "
          f"{', '.join(str(int(y)) for y in imp_years.index)}, i.e. in the OpenAQ data used for January-March 2026. "
          "The mirror holds none. The mirror is CPCB's validated data, OpenAQ the raw feed: in 2025, where both "
          f"exist, OpenAQ has {pct(v25.pm25_le0_share)} of PM2.5 values at or below zero and the mirror is empty at "
          f"{pct(v25.pm25_le0_mirror_empty_share)} of those slots; OpenAQ has PM2.5 > PM10 in "
          f"{pct(v25.openaq_pm25_gt_pm10, 2)} of slots, the mirror in {pct(v25.mirror_pm25_gt_pm10, 2)} "
          "(`docs/mirror-openaq-crosscheck.md` §6, DEC-079). So January-March 2026 is at a lower validation level "
          "than 2015-2025: the flags here remove the impossible and PM2.5 > PM10 values, but not whatever else "
          "CPCB's validation removes. Instrument ceilings are found "
          "from the network-wide histogram (DEC-068): a value that is more than "
          f"{P['flags']['ceiling_detect']['excess']} times as frequent as values of the same precision within "
          f"±{P['flags']['ceiling_detect']['window']} µg/m³, at {P['flags']['ceiling_detect']['min_stations']}+ stations. "
          "Detected ceilings:", "", md(ceil), "",
          "15-minute values removed:", "", md(tot_q.reset_index(), 3), ""]  # fmt: skip

    # 4 hourly flags
    by = hours.groupby(["pollutant", "year"])[
        ["hours", "hours_ratio_flag", "hours_flatline", "hours_ok"]
    ].sum()
    by["ratio_share"] = by.hours_ratio_flag / by.hours
    by["flatline_share"] = by.hours_flatline / by.hours
    L += ["## 4. Hourly flags", "",
          f"*PM2.5 > PM10* at the same station-hour, beyond max({P['flags']['pm25_gt_pm10_tolerance']['abs_ugm3']} µg/m³, "
          f"{pct(P['flags']['pm25_gt_pm10_tolerance']['rel'], 0)} of PM10), flags both pollutants for that hour. "
          f"*Flatline*: identical hourly means for {P['flags']['flatline_min_hours']}+ consecutive hours. Runs of 2-3 "
          "hours occur at the rate expected by chance given the instruments' precision; from 4 hours they do not "
          "(DEC-068). Flagged hours are removed before daily means.", "",
          md(by[["hours", "ratio_share", "flatline_share"]].reset_index(), 4), ""]  # fmt: skip
    top_flat = (
        hours[hours.pollutant == "pm25"]
        .groupby("sid")
        .agg(h=("hours", "sum"), f=("hours_flatline", "sum"))
    )
    top_flat = (top_flat.f / top_flat.h).sort_values(ascending=False)
    L += [f"Flatlined hours are concentrated: the 10 worst stations hold {pct(hours[(hours.pollutant == 'pm25') & hours.sid.isin(top_flat.index[:10])].hours_flatline.sum() / max(1, hours[hours.pollutant == 'pm25'].hours_flatline.sum()))} "
          f"of all flatlined PM2.5 hours; {int((top_flat > 0.05).sum())} stations have more than 5% of their hours flatlined.", ""]  # fmt: skip

    # 5 changepoints
    cpy = (
        cp.assign(year=cp.date.dt.year)
        .groupby(["pollutant", "year"])
        .size()
        .unstack(0, fill_value=0)
    )
    L += ["## 5. Level shifts (changepoints)", "",
          "PELT on each station's weekly departure from its neighbours' median (or its own deseasonalised series "
          f"where it has no two neighbours within {P['flags']['neighbour_radius_km']} km), segments of at least "
          "26 weeks, penalty calibrated so that at most "
          f"{pct(P['flags']['changepoint_false_alarm'], 0)} of block-shuffled (no-shift) series show a changepoint "
          "(DEC-078), steps of at least "
          f"{100 * (np.exp(P['flags']['changepoint_min_shift']) - 1):.0f}% (DEC-072). A step can be a recalibration, an "
          "instrument change or a move, or a real local change beside the monitor; the audit cannot tell which.", "",
          "Penalty calibration (`null_false_alarm` = share of shuffled series with a spurious changepoint; "
          "`real_share_with_shift` = share of real series with one):", "", md(cal, 3), "",
          f"{len(cp)} level shifts at {cp.sid.nunique()} stations. By year:", "",
          md(cpy.reset_index()), "",
          "Size of the steps (% change in level, relative to neighbours):", "",
          md(cp.groupby(["pollutant", "reference"]).shift_pct.describe()[["count", "25%", "50%", "75%"]].reset_index(), 1), ""]  # fmt: skip

    # 6 spatial
    spp = sp[sp.valid_days >= 60]
    sums = spp.groupby("pollutant").agg(
        station_years=("sid", "size"), assessed_neighbours=("neighbour_corr", "count"),
        median_corr=("neighbour_corr", "median"), flagged_neighbours=("flag_neighbour", "sum"),
        assessed_satellite=("sat_ratio", "count"), flagged_satellite=("flag_satellite", "sum"),
    ).reset_index()  # fmt: skip
    L += ["## 6. Spatial consistency", "",
          f"Each station-year (60+ valid days) against its neighbours within {P['flags']['neighbour_radius_km']} km "
          "(correlation of daily log PM with the neighbours' median) and against the satellite (log ratio of its "
          "annual mean to its ACAG V5.GL.06 cell). A station-year is flagged when it is more than "
          f"{P['flags']['robust_z']} robust SDs from that year's network (DEC-071).", "",
          md(sums, 3), ""]  # fmt: skip

    # 7 completeness
    L += ["## 7. Valid station-years (completeness rules)", "",
          "Primary: an hour counts with at least one clean 15-minute value; a valid day has 18 of 24 hours (75%); a "
          "valid year has 75% of days. Sensitivity: 60% and 90% for both levels, and hours needing 3 of 4 "
          "quarter-hours (DEC-069, DEC-073). 2026 counts only January-March.", "",
          md(vs), ""]  # fmt: skip

    # 8 reliability
    r = (
        q25[q25.pollutant == "pm25"]
        .groupby("year")
        .reliability.describe()[["count", "25%", "50%", "75%"]]
    )
    L += ["## 8. Reliability score", "",
          "score = 100 × completeness × (1 − flagged share) × 0.8^(failed checks). Figure 8 "
          "(`reports/figures/fig8_quality_heatmap.png`) shows it for every station and year. PM2.5, station-years "
          "with any data:", "", md(r.reset_index(), 1), ""]  # fmt: skip

    # 9 missingness
    keep = mm[mm.term.str.contains("season|tercile")][
        [
            "model",
            "pollutant",
            "term",
            "Estimate",
            "Std. Error",
            "2.5%",
            "97.5%",
            "n_obs",
            "n_stations",
        ]
    ]
    wint = mo.assign(
        season=mo.month.map(lambda m: "winter (Dec-Feb)" if m in (12, 1, 2) else "rest of year")
    )
    L += ["## 9. Missingness as data", "",
          "Linear probability models of a station-day being missing (not valid), with station fixed effects and "
          "year effects, standard errors clustered by station (DEC-074). Season effects are relative to the "
          "monsoon; pollution-level effects are relative to the cleanest third of days by the neighbours' level. "
          "Coefficients are percentage-point changes in the probability of a missing day (× 100).", "",
          md(keep.assign(**{c: keep[c] * 100 for c in ["Estimate", "Std. Error", "2.5%", "97.5%"]}), 2), "",
          "Share of days missing, pooled:", "",
          md(wint.groupby(["pollutant", "season"]).missing_share.mean().reset_index(), 3), "",
          "What filling missing days from the neighbours does to annual means (valid station-years; bias = naive "
          "mean of observed days ÷ filled mean − 1):", "",
          md(mb.groupby("pollutant").bias_pct.describe()[["count", "25%", "50%", "75%"]].reset_index(), 2), ""]  # fmt: skip

    # 10 EDA
    e = ent[ent.year == "all"][["pollutant", "units", "entrants", "mean_pct", "pct_lo", "pct_hi"]]
    L += ["## 10. Exploratory findings", "",
          "**New stations versus existing ones** (figure `eda_entrants`). In each city and year with both, the new "
          "stations' mean annual level against the existing stations' (all cities pooled):", "", md(e, 1), "",
          "**Ground vs satellite** (figure `eda_ground_vs_satellite`): correlation of log station annual PM2.5 with its "
          "ACAG cell, by year:", "", md(gs[["product", "year", "stations", "r", "r_lo", "r_hi", "median_ratio"]], 3), "",
          "**Seasonal cycles by region** and **raw city trends**: figures `eda_seasonal_regions` and `eda_city_trends`.", ""]  # fmt: skip

    # 11 satellite units
    v = uy[(uy["product"] == "V5GL06") & uy.year.between(2015, 2024)].merge(
        units[["unit_id", "area_km2", "in_primary"]], on="unit_id"
    )
    v = v[v.in_primary]
    v["diff_pct"] = 100 * (v.pm25_popw / v.pm25_area - 1)
    big = v[v.area_km2 > 1000]
    L += ["## 11. Satellite units and the oversized-polygon rule", "",
          f"{int(units.in_primary.sum())} units enter the primary satellite layer; "
          f"{int((~units.in_primary).sum())} buffered NCAP towns without a GHSL centre enter only a sensitivity "
          "analysis (DEC-063). The primary city value is the population-weighted mean over the polygon for every "
          "unit; the area-weighted mean is the sensitivity check (DEC-070). How much the choice matters "
          "(ACAG V5.GL.06, 2015-2024, % difference population- vs area-weighted):", "",
          md(pd.DataFrame({"units": ["all", "over 1,000 km²"],
                           "median_diff_pct": [v.diff_pct.median(), big.diff_pct.median()],
                           "p95_abs_diff_pct": [v.diff_pct.abs().quantile(0.95), big.diff_pct.abs().quantile(0.95)],
                           "median_within_unit_sd": [v.pm25_sd.median(), big.pm25_sd.median()]}), 2), ""]  # fmt: skip

    L += ["## 12. Limits of this audit", "",
          "- A level shift cannot be told apart from a real local change next to a monitor.",
          "- Stations without two neighbours (isolated) get no neighbour check; their changepoints use their own "
          "seasonal cycle and can reflect regional change.",
          "- The satellite check is only as independent as ACAG is of the ground network (it is calibrated to it).",
          f"- {int((stations.coord_quality == 'urban_centre').sum())} stations keep an approximate city point; they "
          "are used for city assignment, not neighbour checks.", ""]  # fmt: skip
    return "\n".join(L)


def main() -> None:
    (DOCS / "audit_report.md").write_text(build(), encoding="utf-8")
    print("wrote docs/audit_report.md")


if __name__ == "__main__":
    main()
