# ------------------------------------------------------------------ downloads


def downloads(D: dict) -> dict[str, pd.DataFrame]:
    u = D["units"][["unit_id", "name"]]
    t = D["trends"]
    g = t[t.unit_id.isin(u.unit_id)].rename(columns={"dw": "deweathered_gam", "dw_other": "deweathered_lightgbm",
                                                      "raw": "raw_mean"})  # fmt: skip
    g["series"] = g.set.map({"all": "all stations", "panel": "stations valid every year 2018-2025"})
    g = g[(g.set == "all") | (g.year >= 2018)]
    g = u.merge(g[["unit_id", "pollutant", "year", "series", "raw_mean", "deweathered_gam", "deweathered_lightgbm", "n_stations"]],
                on="unit_id")  # fmt: skip
    s = u.merge(D["sat"].rename(columns={"pm25_popw": "pm25_popweighted_ugm3"}), on="unit_id")
    e = D["est"].loc[u.unit_id]
    sh = D["shr"].loc[u.unit_id]
    est = pd.DataFrame({"unit_id": u.unit_id.values, "name": u.name.values,
                        "unshrunk_pct": S.pct(e.est), "unshrunk_lo95_pct": S.pct(e.est - 1.96 * e.se),
                        "unshrunk_hi95_pct": S.pct(e.est + 1.96 * e.se), "shrunken_pct": S.pct(sh.post_mean),
                        "shrunken_lo95_pct": S.pct(sh.post_lo95), "shrunken_hi95_pct": S.pct(sh.post_hi95),
                        "note": "relative change against a synthetic comparison; not an effect of NCAP"})  # fmt: skip
    qu = u.merge(D["qual"], on="unit_id")
    return {"ground": g, "satellite": s, "city_estimates": est, "quality": qu}


