def write(path, text: str) -> None:
    wording.check(text, str(path.relative_to(ROOT)))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    from src.common.gate import require_gate

    require_gate("dashboard (Phase 7 and Phase 8 outputs)")
    D = load()
    for sub in ("cities", "data"):
        if (SITE / sub).exists():
            shutil.rmtree(SITE / sub)  # generated; rebuilt in full so a removed unit leaves no stale page
    for _, u in D["units"].iterrows():
        fig, alt = city_figure(u, D)
        S.save(fig, u.slug, directory=SITE / "cities" / "img", formats=("png",), dpi=DPI)
        fig, _ = city_figure(u, D, narrow=True)
        S.save(fig, f"{u.slug}-narrow", directory=SITE / "cities" / "img", formats=("png",), dpi=DPI_NARROW)
        write(SITE / "cities" / f"{u.slug}.qmd", city_page(u, D, alt))
    write(SITE / "index.qmd", index_page(D))
    write(SITE / "about.qmd", about_page())
    write(SITE / "_quarto.yml", QUARTO.format(repo=REPO, osf=OSF))
    for name, df in downloads(D).items():
        (SITE / "data").mkdir(parents=True, exist_ok=True)
        df.round(4).to_csv(SITE / "data" / f"{name}.csv", index=False, lineterminator="\n")
    print(f"dashboard/: {len(D['units'])} city pages, index, about, {len(downloads(D))} downloads")


if __name__ == "__main__":
    main()
