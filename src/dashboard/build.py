"""The read-only city explorer (Phase 9 Part B; DEC-198 to DEC-201): precomputed Quarto site sources.

Writes dashboard/ (committed; rendered by Quarto in the separate `ncap-site` environment, which runs no code):
    _quarto.yml, index.qmd, about.qmd     the site, the alphabetical city list, the data attributions (DEC-200)
    cities/<slug>.qmd, cities/img/<slug>.png   one page per NCAP unit of Layer A (DEC-199)
    data/*.csv                             every number shown, for download (ground series under ODbL 1.0)

Every page carries the "H1 not identified" caveat, generated by the same function as the causal report
(DEC-154). Every page and figure passes the wording check (DEC-193); the build refuses to write otherwise. Cities
are listed alphabetically and never ranked; no page shows a rank, a p-value or a significance label.

    python -m src.dashboard.build      (gated: reads Phase 7 and Phase 8 outputs)
"""

