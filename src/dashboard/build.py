def post_years(cohort: int) -> str:
    """The years a cohort's estimate averages over: listing year to 2024, without 2020 (DEC-139)."""
    ys = [y for y in range(cohort, YEARS_SAT[1] + 1) if y != 2020]
    runs, start = [], ys[0]
    for a, b in zip(ys, ys[1:] + [None], strict=True):
        if b != a + 1:
            runs.append(f"{start}" if start == a else f"{start}–{a}")
            start = b
    return " and ".join(runs)


def fmt(x, nd=1):
    return "–" if pd.isna(x) else f"{x:.{nd}f}"


def city_page(u: pd.Series, D: dict, alt: str) -> str:
    e, sh, avg = D["est"].loc[u.unit_id], D["shr"].loc[u.unit_id], D["avg"]
    ue = S.pct([e.est, e.est - 1.96 * e.se, e.est + 1.96 * e.se])
    us = S.pct([sh.post_mean, sh.post_lo95, sh.post_hi95])
    ua = S.pct([avg["mean"], avg["lo95"], avg["hi95"]])
    t = D["trends"][D["trends"].unit_id == u.unit_id]
    qu = D["qual"][D["qual"].unit_id == u.unit_id]
    has_panel = {p: bool(len(t[(t.pollutant == p) & (t.set == "panel")])) for p in POL}
    has_ground = {p: bool(t[(t.pollutant == p) & (t.set == "all")].raw.notna().any()) for p in POL}
    monitor = "yes" if u.gained_monitor is True or str(u.gained_monitor) == "True" else "no"

    L = ["---", f'title: "{u["name"]}"', "---", "",
         "::: {.callout-important}", "## Read this first", "", D["caveat"], "",
         "Nothing on this page is an effect of NCAP. City-level numbers come from a Bayesian model that pulls noisy "
         "single-city estimates towards the average; cities cannot be ranked from them.", ":::", "",
         "| | |", "|---|---|",
         f"| NCAP cities in this urban centre | {u['name']} |", f"| State | {u.state} |",
         f"| Region | {S.REGION_LABEL.get(u.region, u.region)} |", f"| Listed under NCAP (treated from) | {int(u.cohort_listed)} |",
         f"| Population 2015 (GHSL) | {u.pop_2015:,.0f} |",
         f"| New monitor inside the urban centre, 2019–2024 | {monitor} |", "",
         # one column on phones (≤ 600 px), 2 x 2 elsewhere (DEC-204); the alt text describes both
         "```{=html}", '<figure class="figure column-page">',
         f'<picture><source media="(max-width: 600px)" srcset="img/{u.slug}-narrow.png">'
         f'<img src="img/{u.slug}.png" alt="{html.escape(alt)}" class="img-fluid figure-img"></picture>',
         f"<figcaption>Ground and satellite PM2.5 and the city-level relative change for {html.escape(u['name'])}."
         "</figcaption>", "</figure>", "```", ""]  # fmt: skip
    L += ["## What the charts show", "",
          "- **Ground PM2.5 and PM10** (first two charts): the annual mean over every CPCB station inside the urban centre that was "
          "valid that year, as reported; the same after removing year-to-year weather (deweathered); and, where some stations "
          "were valid every year 2018–2025, those stations alone, deweathered (corrected for weather and for the change in "
          "which stations exist). The numbers along the bottom are the stations behind each year."
          + ("" if any(has_ground.values()) else " **This urban centre has no ground station with a valid year.**")
          + ("" if any(has_panel.values()) else " No station here was valid every year 2018–2025, so there is no "
             "composition-corrected series."),
          "- **Satellite PM2.5** (third chart): ACAG V5.GL.06, weighted by where people live. Descriptive.",
          "- **City-level relative change** (fourth chart): how this urban centre's satellite PM2.5 moved after listing, "
          "against a synthetic comparison built from non-NCAP centres.", ""]  # fmt: skip
    L += ["## City-level relative change (satellite PM2.5)", "",
          "| | estimate | 95% interval |", "|---|---|---|",
          f"| This city, unshrunk (± 1.96 × placebo SE) | {ue[0]:+.1f}% | {ue[1]:+.1f} to {ue[2]:+.1f}% |",
          f"| This city, shrunken (posterior mean; credible interval) | {us[0]:+.1f}% | {us[1]:+.1f} to {us[2]:+.1f}% |",
          f"| Average city-level relative change over the 113 NCAP units | {ua[0]:+.1f}% | {ua[1]:+.1f} to {ua[2]:+.1f}% |", "",
          f"Relative change = the listed unit minus its synthetic comparison, on log satellite PM2.5, averaged over "
          f"{post_years(int(u.cohort_listed))} (2020 excluded), shown as a %. **Not identified as an effect of NCAP.**", ""]  # fmt: skip
    L += ["## Data quality", ""]
    if len(qu):
        w = qu.pivot_table(index="year", columns="pollutant", values=["stations", "median_score"]).sort_index()
        L += ["Stations with any data inside the urban centre, including stations not valid that year (the charts count "
              "valid stations only), and their median reliability score (0–100: completeness × share of unflagged data, "
              "× 0.8 for each failed consistency check).", "",
              "| year | PM2.5 stations with data | PM2.5 median score | PM10 stations with data | PM10 median score |",
              "|---|---|---|---|---|"]  # fmt: skip
        for y, r in w.iterrows():
            get = lambda col, p, r=r: r.get((col, p), np.nan)  # noqa: E731
            L.append(f"| {y} | {fmt(get('stations', 'pm25'), 0)} | {fmt(get('median_score', 'pm25'))} | "
                     f"{fmt(get('stations', 'pm10'), 0)} | {fmt(get('median_score', 'pm10'))} |")  # fmt: skip
        m = qu[qu.year >= 2018]
        if len(m):
            L += ["", f"Median of the yearly median scores, 2018–2025: PM2.5 "
                  f"{fmt(m[m.pollutant == 'pm25'].median_score.median())}, PM10 {fmt(m[m.pollutant == 'pm10'].median_score.median())}."]  # fmt: skip
    else:
        L.append("No CPCB station lies inside this urban centre.")
    L += ["", "## Downloads", "",
          "Every number on this page is in the [data downloads](../about.qmd#downloads). [Back to all cities](../index.qmd)."]
    return "\n".join(L) + "\n"


