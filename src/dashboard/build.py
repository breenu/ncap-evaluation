# ------------------------------------------------------------------ data


def slug(name: str) -> str:
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def display_name(cities: str) -> str:
    return ", ".join(c.strip() for c in cities.split(";"))


def load() -> dict:
    from src.causal import layer_a as A
    from src.causal.causal_report import load as causal_load
    from src.causal.causal_report import wording as dec154
    from src.hierarchical.city_estimates import OUT as HIER

    d = pd.read_csv(A.OUT / "design_units.csv")
    units = d[d.role == "treated"].copy()
    units["name"] = units.ncap_cities.map(display_name)
    units["slug"] = units.name.map(slug)
    if units.slug.duplicated().any():
        raise ValueError("two units share a page name")
    units = units.sort_values("name", key=lambda s: s.str.lower()).reset_index(drop=True)  # alphabetical, never ranked

    t = pd.read_parquet(C.OUT / "trends.parquet")
    t = t[(t.spec == C.PRIMARY.label) & t.year.between(*YEARS_GROUND)]
    sat = pd.read_parquet(PROCESSED / "unit_year_sat.parquet")
    sat = sat[(sat["product"] == "V5GL06") & sat.year.between(*YEARS_SAT)][["unit_id", "year", "pm25_popw"]]
    est = pd.read_csv(HIER / "city_estimates.csv").set_index("unit_id")
    shr = pd.read_csv(HIER / "city_shrunken.csv")
    shr = shr[shr.version == "primary"].set_index("unit_id")
    co = pd.read_csv(HIER / "pool_coefs.csv")
    avg = co[(co.version == "primary") & (co.param == "average city-level relative change")].iloc[0]

    q = pd.read_parquet(PROCESSED / "station_year_quality.parquet")
    reg = pd.read_csv(INTERIM / "station_regions.csv")
    inside = reg[reg.km_to_unit == 0][["sid", "unit_id"]]
    q = q[q.year.between(*YEARS_GROUND)].merge(inside, on="sid")
    qual = (q.groupby(["unit_id", "pollutant", "year"]).reliability.agg(stations="size", median_score="median").reset_index())

    towns = gpd.read_file(INTERIM / "sat_units.gpkg", ignore_geometry=True)
    towns = towns[towns.kind == "town_buffer"].ncap_cities.sort_values().tolist()
    return {"units": units, "trends": t, "sat": sat, "est": est, "shr": shr, "avg": avg, "qual": qual, "towns": towns,
            "caveat": dec154(causal_load())}  # fmt: skip


