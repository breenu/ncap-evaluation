"""The figure catalogue (DEC-194): docs/figures.md, generated from the caption/alt-text sidecars that
`style.save` writes beside every figure. Every caption and alt text passes the wording check (DEC-193) again
here, and the catalogue fails if a listed figure has no sidecar.

    python -m src.viz.catalogue
"""

import json

from src.common.paths import FIGURES, ROOT
from src.viz import wording

# Report order: the eight main figures, the supplementary figures, then the exploratory Phase 3 figures.
ORDER = ["fig1_decomposition", "fig2_station_entry", "fig3_deweathered_annual", "fig3_deweathered",
         "fig3_deweathered_grange_carslaw", "fig4_event_study", "fig5_city_map", "fig6_shrinkage", "fig7_mechanism",
         "fig8_quality_heatmap", "figS1_levels", "figS2_aod_acag", "figS3_decomposition_cities",
         "figS4_decomposition_pm10", "eda_seasonal_regions", "eda_city_trends", "eda_ground_vs_satellite",
         "eda_entrants"]  # fmt: skip
OUT = ROOT / "docs" / "figures.md"


def load() -> list[dict]:
    out = []
    for name in ORDER:
        p = FIGURES / f"{name}.json"
        if not p.exists():
            raise FileNotFoundError(f"no caption/alt-text sidecar for {name}: run its figure module first")
        m = json.loads(p.read_text(encoding="utf-8"))
        for field in ("title", "question", "caption", "alt"):
            wording.check(m[field], f"{name} {field}")
        out.append(m)
    return out


def render(figs: list[dict]) -> str:
    lines = [
        "# Figures",
        "",
        "*Generated by `python -m src.viz.catalogue` from the sidecars that each figure module writes (DEC-194). Do not edit "
        "by hand. Every number in a caption or alt text is formatted from the pipeline outputs the figure draws. Every "
        "figure's text, caption and alt text passed the wording check (`src/viz/wording.py`, DEC-193): nothing is called an "
        "effect of NCAP (H1 is not identified by this design, DEC-151), and no city is ranked.*",
        "",
        "| figure | question it answers | files |",
        "|---|---|---|",
    ]
    for m in figs:
        lines.append(f"| {m['number']} | {m['question']} | [PNG](../reports/figures/{m['name']}.png), "
                     f"[SVG](../reports/figures/{m['name']}.svg) |")  # fmt: skip
    for m in figs:
        lines += [
            "",
            f"## Figure {m['number']}. {m['title']}",
            "",
            f"![{m['alt']}](../reports/figures/{m['name']}.png)",
            "",
            f"**Caption.** {m['caption']}",
            "",
            f"**Alt text.** {m['alt']}",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    figs = load()
    OUT.write_text(render(figs), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(figs)} figures, wording check passed")


if __name__ == "__main__":
    main()
