"""Checks on the Phase 10 documents (DEC-206): no hand-typed result numbers, every variable exists, the
wording rules hold, and every deviation logged in DECISIONS.md is listed in Appendix A.

Hard rule 3 says every number in the report is generated by the pipeline. The prose of the three documents
(`reports/report.qmd`, `summary.qmd`, `policy_brief.qmd`) may therefore contain digits only where they are not
results: years, names (H1, RQ2, DEC-135, PM2.5, V5.GL.06, commit hashes), cross-references (Figure 4,
Table 6, §4) and the conventional confidence levels (95% CI). Everything else must be a `{{< var … >}}`.

The hand-written include files (data sources, references, Appendices A–C) hold facts about the inputs and
the decisions, not results; they must contain no percentages, percentage points or concentrations.
"""

import re

import yaml

from src.common.paths import DOCS, REPORTS
from src.viz import wording

PROSE = ["report.qmd", "summary.qmd", "policy_brief.qmd"]
INCLUDES = ["deviations.md", "sources.md", "references.md", "appendix_b_c.md"]

VAR = re.compile(r"\{\{<\s*var\s+([\w.]+)\s*>\}\}")
SHORTCODE = re.compile(r"\{\{<.*?>\}\}")
STRIP = [
    re.compile(r"\A---\n.*?\n---\n", re.S),  # YAML front matter
    re.compile(r"`[^`]*`"),  # code spans (file names, commands)
    re.compile(r"\$[^$\n]+\$"),  # inline maths
    re.compile(r"<https?://[^>]+>|https?://\S+"),  # URLs
    re.compile(r"\]\([^)]*\)"),  # link and image targets
    re.compile(r"\{[#.][^}]*\}|\{fig-alt=[^}]*\}|\{width=[^}]*\}"),  # attributes
    re.compile(r"@sec-[\w-]+"),  # cross-references
]
ALLOWED = [
    re.compile(r"(?<![\d.])(?:19|20)\d\d(?:[–-](?:19|20)\d\d)?(?!\d|%|\.\d)"),  # years and year ranges
    re.compile(r"\b\d{1,2} (?:January|February|March|April|May|June|July|August|September|October|November|December)\b"),
    re.compile(r"\bDEC-\d+"),  # decision-log entries
    re.compile(r"\b(?:95|90)% (?:CI|CrI|interval|confidence|credible|rank|cluster)", re.I),  # conventional levels
    re.compile(r"\b(?:Figures?|Tables?|Section|Phase|Appendix|step|rule|condition|cohort|group)s? [S]?\d+[a-z]?"
               r"(?:(?:, | and | to |–)[S]?\d+[a-z]?)*", re.I),  # cross-references
    re.compile(r"§\d+(?:\.\d+)*"),
    re.compile(r"^\s*\d+\.\s", re.M),  # numbered lists
]
TOKEN = re.compile(r"(?<![\w.])[+−-]?\d[\d,.]*(?![\w])")  # a stand-alone number (not part of a name such as PM2.5)
RESULT_LIKE = re.compile(r"[+−]\d[\d.,]*\s*%|\d\s*pp\b|\d\s*µg", re.I)  # signed %, percentage points, concentrations


def prose_text(text: str) -> str:
    for p in STRIP:
        text = p.sub(" ", text)
    return SHORTCODE.sub(" ", text)


def typed_numbers(text: str) -> list[str]:
    """Stand-alone numbers in the prose that are neither inside a variable nor in an allowed context."""
    t = prose_text(text)
    for p in ALLOWED:
        t = p.sub(" ", t)
    return [m.group(0) for m in TOKEN.finditer(t)]


def variables() -> dict:
    return yaml.safe_load((REPORTS / "_variables.yml").read_text(encoding="utf-8"))


def lookup(V: dict, key: str):
    x = V
    for k in key.split("."):
        if not isinstance(x, dict) or k not in x:
            raise KeyError(key)
        x = x[k]
    return x


def missing_variables(text: str, V: dict) -> list[str]:
    out = []
    for k in VAR.findall(text):
        try:
            lookup(V, k)
        except KeyError:
            out.append(k)
    return out


def wording_problems(text: str) -> list[str]:
    """The wording check, line by line, on the prose with its variables filled in."""
    V = variables()
    filled = VAR.sub(lambda m: str(lookup(V, m.group(1))), text)
    return [f"{p} | {line.strip()[:120]}" for line in prose_text(filled).split("\n") for p in wording.problems(line)]


def logged_deviations() -> set[str]:
    """DEC numbers whose DECISIONS entry is headed as a deviation."""
    t = (DOCS / "DECISIONS.md").read_text(encoding="utf-8")
    return set(re.findall(r"^\*\*(DEC-\d+)[^\n]*?DEVIATION", t, re.M))


def listed_in_appendix() -> set[str]:
    t = (REPORTS / "deviations.md").read_text(encoding="utf-8")
    out = set()
    for a, b in re.findall(r"DEC-(\d+)(?: to DEC-(\d+))?", t):
        out |= {f"DEC-{i:03d}" for i in range(int(a), int(b or a) + 1)}
    return out


def read(name: str) -> str:
    return (REPORTS / name).read_text(encoding="utf-8")


def all_problems() -> dict[str, list[str]]:
    V = variables()
    out = {}
    for f in PROSE:
        t = read(f)
        out[f"{f}: typed numbers"] = typed_numbers(t)
        out[f"{f}: missing variables"] = missing_variables(t, V)
        out[f"{f}: wording"] = wording_problems(t)
    for f in INCLUDES:
        t = read(f)
        out[f"{f}: result-like numbers"] = RESULT_LIKE.findall(prose_text(t))
        out[f"{f}: wording"] = [p for line in t.split("\n") for p in wording.problems(line)]
    for p in sorted((REPORTS / "_generated").glob("*.md")):
        out[f"{p.name}: wording"] = [x for line in p.read_text(encoding="utf-8").split("\n") for x in wording.problems(line)]
    out["deviations not in Appendix A"] = sorted(logged_deviations() - listed_in_appendix())
    from src.report import readme

    rd = (REPORTS.parent / "README.md").read_text(encoding="utf-8")
    out["README.md: headline findings not as generated"] = [] if readme.block(V) in rd else ["run python -m src.report.values"]
    out["README.md: wording"] = [p for line in readme.block(V).split("\n") for p in wording.problems(line)]
    return out


def main() -> None:
    bad = {k: v for k, v in all_problems().items() if v}
    for k, v in bad.items():
        print(k, v)
    if bad:
        raise SystemExit(1)
    print("report checks passed")


if __name__ == "__main__":
    main()


