"""The README's headline-findings block (Phase 10, DEC-214). Like the report, it holds no typed number: the
block between the markers in README.md is built here from reports/_variables.yml. `python -m src.report.values`
writes it, and `src.report.check` fails if the committed README differs from what this function builds.
"""

START = "<!-- headline findings: generated by `python -m src.report.values`; do not edit by hand -->"
END = "<!-- end of generated headline findings -->"


def block(V: dict) -> str:
    c, co, dw, h, m, u = V["causal"], V["comp"]["primary_pm25"], V["dw"], V["het"], V["maiac"], V["units"]
    lines = [
        f"- **Reported improvements are overstated where I could check them.** In the {co['cities']} NCAP cities with a "
        f"continuous PM2.5 monitor since 2018 ({co['single']} of them with only one), the reported fall of "
        f"{co['reported_abs']} becomes {co['corrected_abs']} once modelled weather and the change in which monitors exist "
        f"are removed. Most of the difference is the changing network: newly opened stations read cleaner than the ones "
        f"already there (H4 supported: {co['h4']} percentage points, 95% CI {co['ci']}).",
        f"- **Weather moves a typical city's annual PM2.5 by a median {dw['weather_pm25']} from one year to the next**, "
        f"so a single year's change says little on its own.",
        f"- **The satellite comparison.** I compared the {u['treated']} urban centres containing {u['cities_in_units']} of "
        f"NCAP's {u['cities_master']} cities with {u['controls']} comparable non-NCAP centres. Satellite PM2.5 fell in both "
        f"groups after 2018: by {c['ncap_fall_abs']} in NCAP units and by {c['pool_fall_abs']} in the comparison pool. {c['sentence']} (Primary estimate {c['att']}, "
        f"95% CI {c['ci']}; the registered pre-trend test failed, p = {c['wald_p']}.)",
        f"- **The satellite product may not be the whole story.** Raw aerosol optical depth, which no ground monitor "
        f"calibrates, shows a smaller relative change on the same units ({m['aod']} against {m['acag']}), for reasons this "
        f"design cannot separate.",
        f"- **No city can be ranked.** A typical city's 95% rank interval spans {h['rank_width']} of {h['units']} places. "
        f"The registered tests for a smaller change in the Indo-Gangetic Plain (H5) and for dust control (H3) came out "
        f"\"{h['h5_verdict']}\" and \"{h['h3_verdict']}\".",
    ]
    return "\n".join([START, "", *lines, "", END])


def sync(text: str, V: dict) -> str:
    """Replace the block between the markers with a freshly built one."""
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block(V) + tail
